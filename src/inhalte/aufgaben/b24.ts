function grundtabelle(id: string, name: string, formel: string, ausdruck: string, kern: string): Aufgabe {
  return {
    id: `b24-tabelle-${id}`,
    typ: 'wahrheitstabelle',
    kann: ['k24-tabellen'],
    titel: `Wahrheitstabelle ${name}`,
    minuten: 1,
    punkte: ausdruck.includes('B') ? 4 : 2,
    operator: 'angeben',
    klausurnah: true,
    stellung: `Gib die Wahrheitstabelle der Funktion **${name}** an (${formel}).`,
    ausdruck,
    notation: 'mathe',
    ausdruckZeigen: false,
    hinweise: TABELLEN_HINWEISE(kern),
    quelle: 'Skript Anhang A',
  };
}

